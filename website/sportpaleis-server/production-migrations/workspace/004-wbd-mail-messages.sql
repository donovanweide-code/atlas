CREATE TABLE IF NOT EXISTS wbd_mail_messages (
  id VARCHAR(80) PRIMARY KEY,
  organization_id VARCHAR(64) NOT NULL,
  mailbox_id VARCHAR(120) NOT NULL,
  thread_id VARCHAR(80) NOT NULL,
  source_key VARCHAR(900) NOT NULL,
  message_id VARCHAR(998) NULL,
  subject VARCHAR(998) NOT NULL,
  snippet VARCHAR(320) NOT NULL,
  body_text MEDIUMTEXT NOT NULL,
  classification VARCHAR(80) NOT NULL,
  priority VARCHAR(20) NOT NULL,
  received_at DATETIME(3) NOT NULL,
  content_hash CHAR(64) NOT NULL,
  message_json JSON NOT NULL,
  created_at DATETIME(3) NOT NULL,
  UNIQUE KEY uq_wbd_mail_source (source_key(700)),
  KEY idx_wbd_mail_recent (organization_id, received_at),
  KEY idx_wbd_mail_thread (thread_id, received_at),
  KEY idx_wbd_mail_mailbox (mailbox_id, received_at),
  KEY idx_wbd_mail_attention (organization_id, priority, received_at),
  KEY idx_wbd_mail_message_id (message_id(255)),
  FULLTEXT KEY ft_wbd_mail_text (subject, snippet, body_text)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
