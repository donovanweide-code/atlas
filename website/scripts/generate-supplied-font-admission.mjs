import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";

import { inspectManagedFontAdmission } from "../src/sportpaleis/managed-font-production.mjs";

const FONT_DIRECTORY = new URL("../public/assets/organizations/sportpaleis/fonts/", import.meta.url);
const OUTPUT = new URL("../src/sportpaleis/supplied-font-admission.generated.mjs", import.meta.url);
const FILENAMES = Object.freeze([
  "VIKING-N.TTF",
  "MyriadPro-SemiboldIt.otf",
  "Schluber.otf",
  "MyriadPro-CondIt.otf",
  "MyriadPro-BoldCondIt.otf",
  "MyriadPro-BoldCond.otf",
  "MyriadPro-It.otf",
  "MyriadPro-BoldIt.otf",
  "MyriadPro-Bold.otf",
  "MyriadPro-Cond.otf",
  "MyriadPro-Regular.otf",
  "Premier League Font 2018.ttf",
]);
const results = [];
for (const filename of FILENAMES) {
  const bytes = await readFile(new URL(filename, FONT_DIRECTORY));
  const sourceSha256 = createHash("sha256").update(bytes).digest("hex").toUpperCase();
  try {
    const admission = inspectManagedFontAdmission(bytes, { representativeValues: ["MW", "VAN DER MEER", "34"] });
    results.push({ filename, sizeBytes: bytes.length, status: "PRODUCTION_EXECUTABLE", mimeType: filename.toLocaleLowerCase("en-US").endsWith(".otf") ? "font/otf" : "font/ttf", ...admission });
  } catch (error) {
    results.push({ filename, sizeBytes: bytes.length, sourceSha256, status: "REJECTED", code: error.code ?? "PRODUCTION_FONT_INVALID", reason: error.message, ...(error.geometryIssues ? { geometryIssues: error.geometryIssues } : {}) });
  }
}
await writeFile(OUTPUT, `// Generated by scripts/generate-supplied-font-admission.mjs. Do not edit manually.\nexport const SPORTPALEIS_SUPPLIED_FONT_ADMISSION = Object.freeze(${JSON.stringify(results, null, 2)});\n`);
console.log(JSON.stringify({ total: results.length, executable: results.filter(({ status }) => status === "PRODUCTION_EXECUTABLE").length, rejected: results.filter(({ status }) => status === "REJECTED").map(({ filename, code }) => ({ filename, code })) }, null, 2));
